fn main() -> anyhow::Result<()> {
    let cli = Cli::parse();
    let module = resolve_module(cli.module)?;

    let pkcs11 = Pkcs11::new(&module)
        .with_context(|| format!("failed to load PKCS#11 module {}", module.display()))?;
    pkcs11.initialize(CInitializeArgs::new(CInitializeFlags::OS_LOCKING_OK))?;

    match cli.command {
        Command::Sign(args) => cmd_sign(&pkcs11, args),
        Command::CertExport(args) => cmd_cert_export(&pkcs11, args),
        Command::CertRevoke(args) => cmd_cert_revoke(&pkcs11, args),
        Command::SubkeyRevoke(args) => cmd_subkey_revoke(&pkcs11, args),
        Command::ListKeys(args) => cmd_list_keys(&pkcs11, args),
        Command::VerifySigningKey(args) => cmd_verify_signing_key(&pkcs11, args),
    }
}

/// Common interface over args structs that carry a subkey selector +
/// subkey auth pair (cert-export and subkey-revoke).
trait HasSubkeyArgs {
    fn subkey_uri(&self) -> Option<&str>;
    fn subkey_label(&self) -> Option<&str>;
    fn subkey_id(&self) -> Option<&str>;
    fn subkey_auto(&self) -> bool;
    fn subkey_pin_file(&self) -> Option<&std::path::Path>;
}

impl HasSubkeyArgs for CertExportArgs {
    fn subkey_uri(&self) -> Option<&str> {
        self.subkey_uri.as_deref()
    }
    fn subkey_label(&self) -> Option<&str> {
        self.subkey_label.as_deref()
    }
    fn subkey_id(&self) -> Option<&str> {
        self.subkey_id.as_deref()
    }
    fn subkey_auto(&self) -> bool {
        self.subkey_auto
    }
    fn subkey_pin_file(&self) -> Option<&std::path::Path> {
        self.subkey_pin_file.as_deref()
    }
}

/// Resolve the subkey key selector from CLI args.
///
/// Returns `None` if no subkey selector was provided.
fn resolve_subkey_selector<A: HasSubkeyArgs>(args: &A) -> anyhow::Result<Option<KeySelector>> {
    if let Some(uri) = args.subkey_uri() {
        return Ok(Some(KeySelector::Uri(uri.parse()?)));
    }
    if let Some(label) = args.subkey_label() {
        return Ok(Some(KeySelector::Label(label.to_owned())));
    }
    if let Some(id_hex) = args.subkey_id() {
        let bytes =
            hex::decode(id_hex).with_context(|| format!("invalid hex in --subkey-id: {id_hex}"))?;
        return Ok(Some(KeySelector::Id(bytes)));
    }
    if args.subkey_auto() {
        return Ok(Some(KeySelector::Auto));
    }
    Ok(None)
}

/// Build a `LoginMode` for the subkey from --subkey-pin-file or
/// `SQ_PKCS11_SUBKEY_PIN`.
fn build_subkey_login<A: HasSubkeyArgs>(args: &A) -> anyhow::Result<LoginMode> {
    if let Some(path) = args.subkey_pin_file() {
        return Ok(LoginMode::Pin(read_pin_file(path)?));
    }
    if let Ok(pin) = std::env::var("SQ_PKCS11_SUBKEY_PIN") {
        return Ok(LoginMode::Pin(pin));
    }
    Ok(LoginMode::None)
}

/// Return the `Duration` from `creation` to its calendar anniversary `n`
/// years later, with Feb 29 → Feb 28 fallback in non-leap target years.
fn years_from(creation: std::time::SystemTime, n: u32) -> anyhow::Result<std::time::Duration> {
    use chrono::{DateTime, Datelike, Utc};
    let secs = creation
        .duration_since(std::time::UNIX_EPOCH)
        .map_err(|_| anyhow::anyhow!("creation time is before the Unix epoch"))?
        .as_secs() as i64;
    let creation_dt = DateTime::<Utc>::from_timestamp(secs, 0)
        .ok_or_else(|| anyhow::anyhow!("creation time is out of the representable range"))?;
    let new_year = creation_dt
        .year()
        .checked_add(n as i32)
        .ok_or_else(|| anyhow::anyhow!("year arithmetic overflowed ({n}y past creation)"))?;
    let expiration_dt = creation_dt.with_year(new_year).or_else(|| {
        // Feb 29 + N years where (year + N) is not a leap year: fall back to Feb 28.
        creation_dt.with_day(28).and_then(|d| d.with_year(new_year))
    });
    let expiration_dt =
        expiration_dt.ok_or_else(|| anyhow::anyhow!("year arithmetic produced an invalid date"))?;
    let delta = (expiration_dt.timestamp() - creation_dt.timestamp()) as u64;
    Ok(std::time::Duration::from_secs(delta))
}

/// Parse a validity-period string into a `Duration` relative to `creation`.
///
/// Accepts:
/// - `Ny` for years (integer N) — calendar-aware: lands on the same
///   wall-clock time of the same calendar date N years after `creation`.
///   Feb 29 falls back to Feb 28 in non-leap target years.
/// - Anything else is delegated to `humantime` (`Nd`, `Nw`, `Nh`, `5d 12h`, …)
///   and treated as an exact fixed duration.
///
/// The Ny branch needs `creation` because the calendar distance between
/// "now" and "N years from now" depends on which leap years fall in the
/// span.  The old `1y = 365.25 days` Julian-year approximation drifted
/// 6h/year off the wall-clock anniversary; the calendar form removes
/// that.
fn parse_validity(s: &str, creation: std::time::SystemTime) -> anyhow::Result<std::time::Duration> {
    let s = s.trim();
    let dur = if let Some(num_str) = s.strip_suffix('y') {
        let n: u32 = num_str.trim().parse().with_context(|| {
            format!(
                "invalid years value in --validity-period {s:?}: \
                 expected a non-negative integer (e.g. 5y, 10y)"
            )
        })?;
        years_from(creation, n).with_context(|| format!("--validity-period {s:?}"))?
    } else {
        humantime::parse_duration(s).with_context(|| {
            format!("invalid --validity-period {s:?}; use Ny, Nw, Nd, or Nh (e.g. 5y, 60d)")
        })?
    };
    // A zero-duration validity period encodes "expired the moment the
    // signature was made" — almost certainly a fat-finger.  Operators
    // who want an unlimited validity should use --no-expiration; we
    // refuse to silently produce a dead-on-arrival certificate.
    if dur.is_zero() {
        anyhow::bail!(
            "--validity-period {s:?} parses to zero — pass --no-expiration if you \
             want an unlimited validity, or a positive duration like 5y or 365d"
        );
    }
    Ok(dur)
}

/// Parse an RFC 3339 timestamp supplied for `flag`, naming the flag in the
/// error so a bad `--revocation-time` doesn't report itself as a bad
/// `--creation-time`.
fn parse_rfc3339_time(flag: &str, ts: &str) -> anyhow::Result<std::time::SystemTime> {
    humantime::parse_rfc3339(ts)
        .with_context(|| format!("invalid {flag} {ts:?}; use RFC 3339, e.g. 2026-04-30T16:29:30Z"))
}

/// Resolve a **mandatory** OpenPGP key-creation time.
///
/// This used to default to `SystemTime::UNIX_EPOCH` when the flag was
/// omitted.  That default was silent and, in the field, wrong: an OpenPGP
/// fingerprint hashes the creation time along with the key material, so a
/// forgotten flag produced real, well-formed signatures carrying an issuer
/// fingerprint that resolves to no published key.  Verification fails with
/// "no public key" — far away from the actual cause, and only after the
/// artefact has shipped.
///
/// A missing timestamp is therefore an error.  Callers that genuinely want
/// the historical behaviour ask for it in full: `--creation-time
/// 1970-01-01T00:00:00Z`.  No opt-in flag is needed for that, and spelling
/// the epoch out leaves the intent in the caller's command line.
fn require_creation_time(
    supplied: Option<&str>,
    flag: &str,
    derive_hint: Option<&str>,
) -> anyhow::Result<std::time::SystemTime> {
    match supplied {
        Some(ts) => parse_rfc3339_time(flag, ts),
        None => Err(missing_creation_time(flag, derive_hint)),
    }
}

/// The diagnostic for an omitted key-creation time.
///
/// Deliberately long: the value cannot be discovered from the HSM (PKCS#11
/// has no notion of an OpenPGP creation time), so an operator who hits this
/// needs to be told where to go and get it.  `derive_hint` carries the
/// per-command shortcut, if the command has one.
fn missing_creation_time(flag: &str, derive_hint: Option<&str>) -> anyhow::Error {
    let hint = match derive_hint {
        Some(h) => format!("\n{h}\n"),
        None => String::new(),
    };
    anyhow::anyhow!(
        "\
{flag} is required.

An OpenPGP fingerprint is a hash over the public key material *and* the key's
creation time, so this timestamp decides the issuer fingerprint embedded in
whatever is signed.  A PKCS#11 token has no notion of an OpenPGP creation
time, so it cannot be read back off the HSM.

Supply the time the key was generated on the HSM, converted to UTC.  On
nShield that is the Security World `gentime` — see NSHIELD.md, \"Reading the
key generation time from the Security World\", which has a CKA_LABEL-to-RFC
3339 recipe.  The value must equal the creation time the published
certificate embeds for this key.
{hint}
Earlier versions of this tool defaulted to 1970-01-01T00:00:00Z here.  That
silently produced signatures whose issuer fingerprint no verifier could
resolve against the published certificate.  If a certificate really was
published with that default, ask for it explicitly:
`{flag} 1970-01-01T00:00:00Z`."
    )
}

/// Refuse to clobber an existing output file *before* any HSM round
/// trip.  Used by every command that writes file output: an accidental
/// rerun of e.g. `sign` against the same `--output` previously failed
/// only after we'd already asked the HSM to sign — wasted work, and an
/// extraneous key-usage audit-log entry for an attempt that never
/// produced an artefact.  Calling this preflight at the top of each
/// command catches the common case before opening any session.
///
/// `write_or_refuse` still does its own atomic create_new check at write
/// time to close the TOCTOU window.  This helper is the fast path.
fn preflight_overwrite(output: Option<&std::path::Path>, force: bool) -> anyhow::Result<()> {
    if force {
        return Ok(());
    }
    let path = match output {
        Some(p) => p,
        None => return Ok(()),
    };
    // `--output -` means stdout; never a file.
    if path == std::path::Path::new("-") {
        return Ok(());
    }
    // try_exists() distinguishes "exists" from "permission-denied while
    // checking"; the latter we surface as an error rather than a refusal.
    match path.try_exists() {
        Ok(true) => anyhow::bail!(
            "refusing to overwrite existing file {}; pass --force to overwrite",
            path.display()
        ),
        Ok(false) => Ok(()),
        Err(e) => Err(anyhow::Error::from(e).context(format!(
            "checking whether {} already exists",
            path.display()
        ))),
    }
}

/// Write `bytes` to `path`, refusing to overwrite an existing file unless
/// `force` is set.  Used by every command that writes a non-stdout output —
/// signatures, certs, revocation files — so a stale `release.asc` cannot be
/// silently replaced by an accidental rerun.
fn write_or_refuse(path: &std::path::Path, bytes: &[u8], force: bool) -> anyhow::Result<()> {
    use std::io::Write as _;
    let result = if force {
        std::fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .open(path)
    } else {
        std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(path)
    };
    let mut file = result.map_err(|e| {
        if e.kind() == std::io::ErrorKind::AlreadyExists {
            anyhow::anyhow!(
                "refusing to overwrite existing file {}; pass --force to overwrite",
                path.display()
            )
        } else {
            anyhow::Error::from(e).context(format!("opening {} for writing", path.display()))
        }
    })?;
    file.write_all(bytes)
        .with_context(|| format!("writing to {}", path.display()))?;
    Ok(())
}

fn resolve_module(from_cli: Option<PathBuf>) -> anyhow::Result<PathBuf> {
    if let Some(p) = from_cli {
        return Ok(p);
    }
    // PKCS11_MODULE_PATH already handled by clap env; reaching here means it
    // was unset. Check the tool-specific fallback variable.
    if let Ok(val) = std::env::var("SQ_PKCS11_MODULE") {
        return Ok(PathBuf::from(val));
    }
    anyhow::bail!(
        "PKCS#11 module not specified.\n\
         Use -m/--module <path>, or set PKCS11_MODULE_PATH or SQ_PKCS11_MODULE.\n\
         Example: -m /opt/nfast/toolkits/pkcs11/libcknfast.so"
    )
}

