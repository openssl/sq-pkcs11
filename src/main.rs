#[derive(clap::Args)]
struct SignArgs {
    #[command(flatten)]
    key: KeySelectionArgs,

    #[command(flatten)]
    auth: AuthArgs,

    /// File to sign.
    #[arg(value_name = "FILE")]
    file: PathBuf,

    /// Write signature to this path (default: <input>.asc).  Pass `-` to
    /// stream the signature to stdout instead of writing a file — useful
    /// when the wrapping script (e.g. a `git config gpg.program` shim)
    /// needs to capture the signature without a temp-file dance.
    #[arg(long, short = 'o', value_name = "FILE")]
    output: Option<PathBuf>,

    /// Produce binary signature instead of ASCII-armored.
    /// (Default output is ASCII-armored, matching GnuPG and Sequoia conventions.)
    ///
    /// Binary detached signatures are what `gpg --no-armor -sbo` produces and
    /// what `rpmsign --addsign` embeds verbatim in a package header.
    #[arg(long, conflicts_with = "cleartext")]
    binary: bool,

    /// Emit an OpenPGP Cleartext Signature Framework document (RFC 9580 §7)
    /// instead of a detached signature: the input text, followed by an
    /// armored signature over it, in one file.
    ///
    /// This is the form `gpg --clearsign` produces, and the form apt prefers
    /// for a repository's `InRelease` file.
    ///
    /// `--output` is mandatory here.  A cleartext document is a *signed
    /// message*, not a detached signature, so writing it to the usual
    /// `<input>.asc` default would invite publishing it where a detached
    /// signature is expected — where every verifier would reject it.
    ///
    /// The framework does not sign trailing whitespace and requires a final
    /// newline, so line-ending whitespace is trimmed and a missing final
    /// newline added in the emitted copy of the text; the emitted text is
    /// exactly what was signed.
    #[arg(long, requires = "output")]
    cleartext: bool,

    /// Overwrite the output file if it already exists.  Without this flag,
    /// sq-pkcs11 refuses to overwrite an existing file — protects against
    /// accidentally clobbering a previously-signed release artefact.
    #[arg(long)]
    force: bool,

    /// Key creation time used to compute the OpenPGP fingerprint embedded in
    /// the signature's issuer field (RFC 3339, e.g. 2026-04-30T16:29:30Z).
    ///
    /// Must match the value used during cert-export so verifiers can resolve
    /// the issuer fingerprint to the distributed certificate.
    ///
    /// Precedence: an explicit --creation-time always wins (and warns if it
    /// disagrees with the matching key in --input-cert).  Otherwise, if
    /// --input-cert is given the creation time is derived from the cert.
    /// Supplying neither is an error — there is no default, because a wrong
    /// creation time yields a wrong issuer fingerprint and thus a signature
    /// no verifier can attribute to the published certificate.
    #[arg(long, value_name = "TIMESTAMP")]
    creation_time: Option<String>,

    /// Published certificate to derive the key-creation time from when
    /// --creation-time is not given (RFC 3339 path otherwise).
    ///
    /// The signing (sub)key is located in the cert by matching the HSM key's
    /// public material — RSA modulus+exponent, or EC curve+point — and its
    /// embedded creation time is used so the signature's issuer fingerprint
    /// equals the published (sub)key's by construction.  This is the robust
    /// way to sign release artefacts and git tags: no timestamp to remember,
    /// rotation-safe, and it cannot select the wrong subkey.
    ///
    /// Errors if no key in the cert matches the HSM key's material — it never
    /// silently falls back to the Unix-epoch default.
    #[arg(long, value_name = "FILE")]
    input_cert: Option<PathBuf>,

    /// Refuse to sign unless the HSM key is exactly this algorithm and size.
    ///
    /// A deployment's key policy is not something this tool can infer, and
    /// getting it wrong is expensive to undo: rpm 4.16 (EL9) cannot verify
    /// ECDSA at all, so a package signed with the wrong key type is only
    /// discovered by the consumer.  Stating the requirement at the call site
    /// turns that into a refusal to sign.
    ///
    /// The match is exact, not a minimum: `rsa4096` accepts RSA-4096 and
    /// rejects RSA-3072 *and* RSA-8192.  A policy says which key is in use,
    /// not which keys would be strong enough.
    #[arg(long, value_name = "ALGO", value_enum)]
    require_key_algo: Option<RequiredKeyAlgo>,

    /// Skip the signer-validity pre-flight that --input-cert performs.
    ///
    /// With --input-cert, sign first proves the HSM key is a *current valid
    /// signer* in that certificate — not revoked, not expired, and carrying
    /// the signing flag — because matching the key material alone would still
    /// accept a rotated-out subkey that is deliberately kept in the cert so
    /// old signatures keep verifying.
    ///
    /// Pass this only to sign deliberately with a key the cert no longer
    /// advertises as current; the resulting signature will be rejected by
    /// verifiers applying the same policy.
    #[arg(long, requires = "input_cert")]
    no_verify_signing_key: bool,
}

/// Key algorithms `sign --require-key-algo` can be pinned to.
///
/// Deliberately an enum rather than a free-form string: the values are the
/// algorithms this tool supports at all, so `--help` lists them and a typo is
/// a parse error instead of a policy check that silently never matches.
#[derive(Clone, Copy, Debug, PartialEq, Eq, clap::ValueEnum)]
enum RequiredKeyAlgo {
    Rsa2048,
    Rsa3072,
    Rsa4096,
    P256,
    P384,
    P521,
}

impl RequiredKeyAlgo {
    fn as_str(self) -> &'static str {
        match self {
            Self::Rsa2048 => "RSA-2048",
            Self::Rsa3072 => "RSA-3072",
            Self::Rsa4096 => "RSA-4096",
            Self::P256 => "ECDSA P-256",
            Self::P384 => "ECDSA P-384",
            Self::P521 => "ECDSA P-521",
        }
    }
}

